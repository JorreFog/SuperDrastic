#!/usr/bin/env python3
"""Build dsreal: a realistic DS stress ROM (scenes modelled on real games; see README.md).

    build.py   -> out/dsreal.nds (realistic, level 5, every scene in turn, loops = soak),
                  out/dsreal-L1..L10.nds (load levels), out/dsreal-race.nds / -action / -town (one scene forever),
                  and a .phases.tsv beside each (start_seconds<TAB>name, for stress-run.sh / summarize.py)
Needs clang + ld.lld + llvm-objcopy (armv5te ARM9 mostly Thumb with ARM hot paths, armv4t ARM7). Own code, GPL-3.0.
"""
import math, os, random, struct, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROBE = os.environ.get("DSREAL_PROBE") == "1"   # the companion probe block (out-probe/)
OUT = os.path.join(HERE, "out-probe" if PROBE else "out"); os.makedirs(OUT, exist_ok=True)
def fx(v): return int(round(v * 4096))

# ---- tables.h ----
sintab = [fx(math.sin(i * 2 * math.pi / 1024)) for i in range(1024)]
atantab = [int(round(math.atan(i / 256) / (2 * math.pi) * 1024)) for i in range(257)]
def proj(fovy, near, far, aspect=256 / 192):
    top = near * math.tan(math.radians(fovy / 2)); right = top * aspect
    return [fx(near / right), 0, 0, 0, 0, fx(near / top), 0, 0, 0, 0, fx(-(far + near) / (far - near)), fx(-1),
            0, 0, fx(-2 * far * near / (far - near)), 0]
FONT = {  # 3x5, rows top to bottom
 ' ':"000000000000000", '0':"111101101101111", '1':"010110010010111", '2':"111001111100111", '3':"111001111001111",
 '4':"101101111001001", '5':"111100111001111", '6':"111100111101111", '7':"111001001001001", '8':"111101111101111",
 '9':"111101111001111", 'A':"111101111101101", 'B':"110101110101110", 'C':"111100100100111", 'D':"110101101101110",
 'E':"111100111100111", 'F':"111100111100100", 'G':"111100101101111", 'H':"101101111101101", 'I':"111010010010111",
 'J':"001001001101111", 'K':"101101110101101", 'L':"100100100100111", 'M':"101111111101101", 'N':"110101101101101",
 'O':"111101101101111", 'P':"111101111100100", 'Q':"111101101111001", 'R':"111101110101101", 'S':"111100111001111",
 'T':"111010010010010", 'U':"101101101101111", 'V':"101101101101010", 'W':"101101111111101", 'X':"101101010101101",
 'Y':"101101010010010", 'Z':"111001010100111", '%':"101001010100101", ':':"000010000010000", '-':"000000111000000",
 '.':"000000000000010", '/':"001001010100100", ',':"000000000010100", '!':"010010010000010", '?':"111001011000010",
 "'":"010010000000000", '=':"000111000111000", '+':"000010111010000"}
font = [int(FONT.get(chr(32 + i), "0" * 15), 2) for i in range(64)]
with open(os.path.join(HERE, "tables.h"), "w") as f:
    f.write("/* generated by build.py */\n#pragma once\n")
    f.write("static const short sintab[1024] = {%s};\n" % ",".join(map(str, sintab)))
    f.write("static const unsigned char atantab[257] = {%s};\n" % ",".join(map(str, atantab)))
    f.write("static const int proj_race[16] = {%s};\n" % ",".join(map(str, proj(55, 0.5, 110))))
    f.write("static const int proj_town[16] = {%s};\n" % ",".join(map(str, proj(30, 1.0, 64))))
    f.write("static const unsigned short font3x5[64] = {%s};\n" % ",".join(map(str, font)))

# ---- compile + link ----
CF = ["-O2", "-fno-unwind-tables", "-fno-asynchronous-unwind-tables", "-ffreestanding", "-fno-builtin", "-nostdlib",
      "-Wall", "-Wno-unused-function", "-Wno-misleading-indentation", "-fno-jump-tables"]
T9 = ["--target=armv5te-none-eabi", "-mfloat-abi=soft"]
T7 = ["--target=armv4t-none-eabi", "-mfloat-abi=soft"]
def run(cmd): subprocess.run(cmd, check=True, cwd=HERE)
def cc(src, obj, tgt, thumb=True, extra=()):
    if PROBE and src.endswith(".c"): extra = (*extra, "-DDSREAL_PROBE=1")
    run(["clang", *tgt, "-mthumb" if thumb else "-marm", *(CF if src.endswith(".c") else []), *extra, "-c", src, "-o", os.path.join(OUT, obj)])
    return os.path.join(OUT, obj)
LD9 = """ENTRY(_start)
SECTIONS {
  . = 0x02000000;
  .text : { *(.text.start) *(.text*) *(.rodata*) }
  .data : { *(.data*) }
  . = ALIGN(4);
  __itcm_lma = .;
  .itcm 0x01FF8000 : AT(__itcm_lma) { __itcm_start = .; *(.itcm*) . = ALIGN(4); __itcm_end = .; }
  .bss (ALIGN(__itcm_lma + SIZEOF(.itcm), 32)) (NOLOAD) : { __bss_start = .; *(.bss*) *(COMMON) . = ALIGN(4); __bss_end = .; }
  /DISCARD/ : { *(.ARM.exidx*) *(.ARM.extab*) *(.ARM.attributes) }
}
"""
def ldscript(name, text):
    p = os.path.join(OUT, name); open(p, "w").write(text); return p
def link(objs, script, elf, binf):
    run(["ld.lld", "-T", script, *objs, "-o", os.path.join(OUT, elf)])
    run(["llvm-objcopy", "-O", "binary", os.path.join(OUT, elf), os.path.join(OUT, binf)])
    return open(os.path.join(OUT, binf), "rb").read()

objs9 = [cc("crt9.s", "crt9.o", T9, False)] + [cc(s, s[:-2] + ".o", T9) for s in ("core9.c", "main9.c", "race.c", "action.c", "town.c", "work.c")]
objs9.append(cc("div.c", "div9.o", T9, False))
arm9 = bytearray(link(objs9, ldscript("ld9.ld", LD9), "arm9.elf", "arm9.bin"))
assert arm9[4:8] == b"REAL", "config block not at offset 4"
LDO = LD9.split("__itcm_lma")[0].replace("ENTRY(_start)", "").replace("0x02000000", "0x02200000") + \
      "  .bss : { *(.bss*) *(COMMON) }\n  /DISCARD/ : { *(.ARM.exidx*) *(.ARM.extab*) *(.ARM.attributes) }\n}\n"
ovl = []
for n in (0, 1):
    o = cc("ovl.c", "ovl%d.o" % n, T9, True, ["-DOVLN=%d" % n])
    b = link([o, os.path.join(OUT, "div9.o")], ldscript("ldo.ld", LDO), "ovl%d.elf" % n, "ovl%d.bin" % n)
    assert len(b) <= 0x4000, "overlay too big"; ovl.append(b)
LD7 = """ENTRY(_start7)
SECTIONS {
  . = 0x02380000;
  .text : { *(.text.start) *(.text*) *(.rodata*) }
  .data : { *(.data*) }
  . = ALIGN(32); __bss_start = .;
  .bss : { *(.bss*) *(COMMON) }
  . = ALIGN(4); __bss_end = .;
  /DISCARD/ : { *(.ARM.exidx*) *(.ARM.extab*) *(.ARM.attributes) }
}
"""
objs7 = [cc("crt7.s", "crt7.o", T7, False), cc("main7.c", "main7.o", T7, True), cc("div.c", "div7.o", T7, False)]
arm7 = link(objs7, ldscript("ld7.ld", LD7), "arm7.elf", "arm7.bin")

# ---- data: texture sets, map chunks, the ADPCM stream ----
def texset(seed):
    R = random.Random(seed); tex = bytearray(0x6000); idx = bytearray(0x800); pal = bytearray(0x600)
    def p16(off, i, v): struct.pack_into("<H", tex, off + i * 2, v)
    for y in range(64):                                              # road: direct colour
        for x in range(64):
            g = 10 + R.randrange(4) + (8 if x in (31, 32) and (y // 8) % 2 else 0)
            p16(0x0000, y * 64 + x, 0x8000 | g | g << 5 | (g + 1) << 10)
    for i in range(64 * 64 // 2): tex[0x2000 + i] = R.randrange(16) | R.randrange(16) << 4   # grass: 16-colour
    for y in range(32):                                              # smoke: A3I5, a soft disc
        for x in range(32):
            d = math.hypot(x - 15.5, y - 15.5) / 16; a = max(0, int(7 * (1 - d)))
            tex[0x2800 + y * 32 + x] = (int(31 * (1 - min(d, 1))) & 31) | a << 5
    for i in range(64 * 64): tex[0x2C00 + i] = (i * 7 + seed + (i >> 6) * 3) & 0xFF            # body: 256-colour
    for i in range(32 * 32): tex[0x3C00 + i * 4: 0x3C00 + i * 4 + 4] = bytes(R.randrange(256) for _ in range(4))   # 4x4 texels
    for i in range(32 * 32): struct.pack_into("<H", idx, i * 2, (R.randrange(120) & 0x3FFF) | (2 << 14))
    for i in range(32 * 32): tex[0x4C00 + i] = (R.randrange(8)) | (8 + R.randrange(24)) << 3       # glass: A5I3
    for f in range(8):                                               # NPC frames: 16x32 4bpp, a figure
        for y in range(32):
            for x in range(0, 16, 2):
                inside = lambda xx: abs(xx - 7.5) < 3 + (y > 12) * 2 - (y > 26) * 2 and y > 2
                a = (1 + (y + f) % 7) if inside(x) else 0; b = (1 + (y + f) % 7) if inside(x + 1) else 0
                tex[0x5000 + f * 256 + y * 8 + x // 2] = a | b << 4
    for y in range(64):                                              # tree: A3I5 trunk + crown
        for x in range(32):
            crown = math.hypot(x - 15.5, (y - 22) * 0.8) < 15; trunk = abs(x - 15.5) < 3 and y > 30
            tex[0x5800 + y * 32 + x] = ((R.randrange(32)) | 7 << 5) if (crown or trunk) else 0
    def pal16(off, n, f):
        for i in range(n): struct.pack_into("<H", pal, off + i * 2, f(i) & 0x7FFF)
    rgb = lambda r, g, b: int(r) | int(g) << 5 | int(b) << 10
    pal16(0x000, 16, lambda i: rgb(4 + i // 3, 14 + i, 4 + (seed & 3)))
    pal16(0x020, 32, lambda i: rgb(16 + i // 2, 16 + i // 2, 16 + i // 2))
    pal16(0x060, 256, lambda i: rgb((i * 3 + seed) & 31, (i >> 3) & 31, (31 - i) & 31))
    pal16(0x260, 256, lambda i: rgb((i * 5) & 31, (i * 2 + 8) & 31, (i + seed * 4) & 31))
    pal16(0x460, 8, lambda i: rgb(16 + i * 2, 24, 31))
    pal16(0x480, 16, lambda i: rgb(31 - i * 2, 10 + i, 8 + i))
    pal16(0x500, 32, lambda i: rgb(3 + i // 4, 10 + i // 2, 3))
    return bytes(tex) + bytes(idx) + bytes(pal)
def chunk(n):
    R = random.Random(1000 + n); c = bytearray(R.randrange(256) for _ in range(0x2000))
    c[0] = n & 3
    for y in range(32):
        for x in range(32): c[64 + y * 32 + x] = 1 if (x in (0, 31) or y in (0, 31) or R.random() < 0.06) else 0
    return bytes(c)
def adpcm_stream(nbytes):
    steps = [7,8,9,10,11,12,13,14,16,17,19,21,23,25,28,31,34,37,41,45,50,55,60,66,73,80,88,97,107,118,130,143,157,173,190,
             209,230,253,279,307,337,371,408,449,494,544,598,658,724,796,876,963,1060,1166,1282,1411,1552,1707,1878,2066,
             2272,2499,2749,3024,3327,3660,4026,4428,4871,5358,5894,6484,7132,7845,8630,9493,10442,11487,12635,13899,
             15289,16818,18500,20350,22385,24623,27086,29794,32767]
    adj = [-1,-1,-1,-1,2,4,6,8]
    chords = [(220, 277, 330), (196, 247, 294), (175, 220, 262), (196, 247, 330)]
    pred, idx, out, nib = 0, 0, bytearray(), []
    for i in range(nbytes * 2):
        t = i / 32768; ch = chords[int(t / 2) % 4]
        env = 0.5 + 0.5 * math.sin(2 * math.pi * t * 0.5)
        v = sum(math.sin(2 * math.pi * f * t) for f in ch) / 3 * 9000 * env + math.sin(2 * math.pi * ch[0] / 2 * t) * 4000
        d = int(v) - pred; step = steps[idx]; n = 0
        if d < 0: n = 8; d = -d
        diff = step >> 3
        if d >= step: n |= 4; d -= step; diff += step
        if d >= step >> 1: n |= 2; d -= step >> 1; diff += step >> 1
        if d >= step >> 2: n |= 1; diff += step >> 2
        pred = max(-32768, min(32767, pred - diff if n & 8 else pred + diff))
        idx = max(0, min(88, idx + adj[n & 7])); nib.append(n)
        if len(nib) == 2: out.append(nib[0] | nib[1] << 4); nib = []
    return bytes(out)
DATA = {0x080000: ovl[0], 0x088000: ovl[1]}
for s in range(4): DATA[0x090000 + s * 0x10000] = texset(s)
for n in range(32): DATA[0x0D0000 + n * 0x2000] = chunk(n)
cache = os.path.join(HERE, "out", "stream.adpcm")
if not os.path.exists(cache): open(cache, "wb").write(adpcm_stream(0x40000))
DATA[0x110000] = open(cache, "rb").read()
ROMSIZE = 0x200000

def crc16(data, crc=0xFFFF):
    for b in data:
        crc ^= b
        for _ in range(8): crc = (crc >> 1) ^ 0xA001 if crc & 1 else crc >> 1
    return crc

SCENES = [("race", 1500), ("action", 1200), ("town", 1500), ("ohg", 1500)]
FPS = 59.8261
def rom(name, mode, scene, level, loops=12):
    a9 = bytearray(arm9)
    struct.pack_into("<5I", a9, 8, mode, scene, level, 0, 0)
    a9 += b"\0" * (-len(a9) % 0x200)
    a9off = 0x8000; a7off = a9off + len(a9)
    body = bytearray(ROMSIZE)
    body[a9off:a9off + len(a9)] = a9; body[a7off:a7off + len(arm7)] = arm7
    assert a7off + len(arm7) < 0x80000
    for off, blob in DATA.items(): body[off:off + len(blob)] = blob
    h = bytearray(0x200)
    h[0:12] = b"DSREAL".ljust(12, b"\0"); h[12:16] = b"REAL"; h[16:18] = b"00"
    h[0x14] = 4                                              # 2 MB
    struct.pack_into("<8I", h, 0x20, a9off, 0x02000000, 0x02000000, len(a9), a7off, 0x02380000, 0x02380000, len(arm7))
    struct.pack_into("<2I", h, 0x60, 0x00586000, 0x001808F8)
    struct.pack_into("<2I", h, 0x80, ROMSIZE, 0x200)
    struct.pack_into("<H", h, 0x15E, crc16(h[:0x15E]))
    body[0:0x200] = h
    open(os.path.join(OUT, name), "wb").write(body)
    # phase table (emulated frames at 59.83 fps; a scene's start adds a few frames of loading)
    t, rows = 0.0, []
    for _ in range(loops):
        for i, (sn, fr) in enumerate(SCENES):
            if mode == 1 and i != scene: continue
            rows.append("%.1f\t%s" % (t, sn)); t += fr / FPS + 0.05
    open(os.path.join(OUT, name[:-4] + ".phases.tsv"), "w").write("\n".join(rows) + "\n")
    return name

names = [rom("dsreal.nds", 0, 0, 5)]
names += [rom("dsreal-L%d.nds" % l, 0, 0, l) for l in range(1, 11)]
names += [rom("dsreal-%s.nds" % n, 1, i, 5) for i, (n, _) in enumerate(SCENES)]
print("arm9 %d bytes, arm7 %d, overlays %d/%d ->" % (len(arm9), len(arm7), len(ovl[0]), len(ovl[1])), " ".join(names))
